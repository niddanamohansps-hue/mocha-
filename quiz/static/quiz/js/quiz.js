/**
 * Ultimate Dev Quiz Engine - Frontend Coordinator (Classroom Edition)
 * Coordinates student onboarding, question state, timers, scoring APIs, and live standings.
 */

document.addEventListener('DOMContentLoaded', () => {
    // --- Quiz State Variables ---
    let questionsList = [];
    let currentQuestionIndex = 0;
    let score = 0;
    let selectedOption = null;
    let isSubmitted = false;
    let timerInterval = null;
    let timeLeft = 15;
    const SECONDS_PER_QUESTION = 15;

    // Student profile details
    let studentName = "";
    let studentId = "";

    // --- DOM Elements ---
    // Screens
    const welcomeScreen = document.getElementById('welcomeScreen');
    const questionScreen = document.getElementById('questionScreen');
    const resultsScreen = document.getElementById('resultsScreen');
    
    // Welcome Controls & Registration Inputs
    const startBtn = document.getElementById('startBtn');
    const studentNameInput = document.getElementById('studentNameInput');
    const studentIdInput = document.getElementById('studentIdInput');
    
    // Quiz Dashboard Controls
    const questionBadge = document.getElementById('questionBadge');
    const liveScoreBadge = document.getElementById('liveScoreBadge');
    const questionText = document.getElementById('questionText');
    const optionsContainer = document.getElementById('optionsContainer');
    const submitBtn = document.getElementById('submitBtn');
    const nextBtn = document.getElementById('nextBtn');
    const progressBar = document.getElementById('progressBar');
    
    // Timer Widget
    const timerWidget = document.getElementById('timerWidget');
    const timerText = document.getElementById('timerText');
    
    // Results Controls & Info
    const resultsPercent = document.getElementById('resultsPercent');
    const resultsScoreText = document.getElementById('resultsScoreText');
    const feedbackTitle = document.getElementById('feedbackTitle');
    const resultsSummaryText = document.getElementById('resultsSummaryText');
    const gaugeFill = document.getElementById('gaugeFill');
    const restartBtn = document.getElementById('restartBtn');
    
    // Results Stats
    const statsCorrect = document.getElementById('statsCorrect');
    const statsWrong = document.getElementById('statsWrong');
    const statsTime = document.getElementById('statsTime');

    // Leaderboard table body
    const leaderboardBody = document.getElementById('leaderboardBody');

    // --- On Load Initializations ---
    loadLeaderboard();

    // --- Helper Functions ---
    
    /**
     * Retrieves the CSRF token generated by Django.
     */
    function getCsrfToken() {
        const csrfInput = document.querySelector('[name=csrfmiddlewaretoken]');
        if (csrfInput) {
            return csrfInput.value;
        }
        // Fallback to cookie search if input not found
        let cookieValue = null;
        if (document.cookie && document.cookie !== '') {
            const cookies = document.cookie.split(';');
            for (let i = 0; i < cookies.length; i++) {
                const cookie = cookies[i].trim();
                if (cookie.substring(0, 10) === 'csrftoken=') {
                    cookieValue = decodeURIComponent(cookie.substring(10));
                    break;
                }
            }
        }
        return cookieValue;
    }

    /**
     * Switches the active screen with a subtle CSS fade.
     */
    function switchScreen(activeScreen) {
        [welcomeScreen, questionScreen, resultsScreen].forEach(screen => {
            screen.classList.remove('active');
        });
        activeScreen.classList.add('active');
        
        // Control timer widget visibility based on screen
        if (activeScreen === questionScreen) {
            timerWidget.classList.add('active');
        } else {
            timerWidget.classList.remove('active');
        }
    }

    /**
     * Fetches current classroom leaderboard standings and populates the table.
     */
    async function loadLeaderboard() {
        try {
            const response = await fetch('/api/leaderboard/');
            if (!response.ok) throw new Error('Could not pull standings data.');
            const data = await response.json();
            
            const leaderboard = data.leaderboard;
            if (leaderboard.length === 0) {
                leaderboardBody.innerHTML = `
                    <tr>
                        <td colspan="6" class="table-empty">
                            <i class="fa-solid fa-trophy" style="font-size: 24px; color: var(--text-muted); display:block; margin-bottom: 8px;"></i>
                            No scores recorded yet. Be the first to take the challenge!
                        </td>
                    </tr>
                `;
                return;
            }

            leaderboardBody.innerHTML = '';
            leaderboard.forEach((attempt, index) => {
                const rank = index + 1;
                let rankHTML = '';
                
                // Styling ranks
                if (rank === 1) rankHTML = `<span class="rank-badge rank-1"><i class="fa-solid fa-crown"></i> 1</span>`;
                else if (rank === 2) rankHTML = `<span class="rank-badge rank-2">2</span>`;
                else if (rank === 3) rankHTML = `<span class="rank-badge rank-3">3</span>`;
                else rankHTML = `<span class="rank-badge rank-other">${rank}</span>`;

                // Grading metrics
                let grade = 'F';
                let gradeClass = 'grade-f';
                
                if (attempt.percentage >= 90) { grade = 'A+'; gradeClass = 'grade-a'; }
                else if (attempt.percentage >= 80) { grade = 'A'; gradeClass = 'grade-a'; }
                else if (attempt.percentage >= 65) { grade = 'B'; gradeClass = 'grade-b'; }
                else if (attempt.percentage >= 50) { grade = 'C'; gradeClass = 'grade-c'; }

                const row = document.createElement('tr');
                row.innerHTML = `
                    <td>${rankHTML}</td>
                    <td style="font-weight: 600; color:#fff;">${escapeHTML(attempt.student_name)}</td>
                    <td style="color: var(--text-muted); font-family: monospace;">${escapeHTML(attempt.student_id)}</td>
                    <td style="text-align: center; font-weight: 700;">${attempt.score}/${attempt.total_questions}</td>
                    <td style="text-align: center;"><span class="grade-badge ${gradeClass}">${grade}</span></td>
                    <td style="text-align: right; color: var(--text-muted); font-size:11px;">${attempt.timestamp}</td>
                `;
                leaderboardBody.appendChild(row);
            });
        } catch (error) {
            console.error('Leaderboard Fetch Error:', error);
            leaderboardBody.innerHTML = `
                <tr>
                    <td colspan="6" class="table-empty" style="color: var(--danger);">
                        <i class="fa-solid fa-triangle-exclamation" style="display:block; margin-bottom:8px;"></i>
                        Error rendering leaderboard standings.
                    </td>
                </tr>
            `;
        }
    }

    // --- Core Operations ---

    /**
     * Initializes the quiz, fetches questions from the Django backend.
     */
    async function loadQuiz() {
        try {
            const response = await fetch('/api/questions/');
            if (!response.ok) {
                throw new Error('Failed to retrieve quiz questions.');
            }
            const data = await response.json();
            questionsList = data.questions;
            
            if (questionsList.length === 0) {
                questionText.textContent = "No questions found in database. Please seed backend database.";
                return;
            }
            
            // Launch the first question
            currentQuestionIndex = 0;
            score = 0;
            liveScoreBadge.textContent = `Score: 0`;
            switchScreen(questionScreen);
            displayQuestion();
        } catch (error) {
            console.error('Quiz Loading Error:', error);
            questionText.textContent = "Error loading questions. Please reload or check server logs.";
        }
    }

    /**
     * Renders the current question and populates the glass options.
     */
    function displayQuestion() {
        if (currentQuestionIndex >= questionsList.length) {
            endQuiz();
            return;
        }

        const question = questionsList[currentQuestionIndex];
        
        // Reset interactive state
        selectedOption = null;
        isSubmitted = false;
        submitBtn.disabled = true;
        submitBtn.classList.remove('hidden');
        nextBtn.classList.add('hidden');
        
        // Update linear progress bar at the top of the card
        const progressPercent = (currentQuestionIndex / questionsList.length) * 100;
        progressBar.style.width = `${progressPercent}%`;

        // Update headers & meta tags
        questionBadge.textContent = `Question ${currentQuestionIndex + 1}/${questionsList.length}`;
        questionText.textContent = question.text;

        // Render option buttons
        optionsContainer.innerHTML = '';
        const letters = { 'Option1': 'A', 'Option2': 'B', 'Option3': 'C', 'Option4': 'D' };
        
        Object.entries(question.options).forEach(([key, text]) => {
            const optionBtn = document.createElement('button');
            optionBtn.className = 'option-btn';
            optionBtn.dataset.option = key;
            
            optionBtn.innerHTML = `
                <span class="option-letter">${letters[key]}</span>
                <span class="option-content">${escapeHTML(text)}</span>
                <span class="feedback-icon"><i class="fa-solid"></i></span>
            `;
            
            optionBtn.addEventListener('click', () => selectOption(optionBtn, key));
            optionsContainer.appendChild(optionBtn);
        });

        // Start Question Timer
        startTimer();
    }

    /**
     * Utility function to escape HTML special characters.
     */
    function escapeHTML(str) {
        return str
            .replace(/&/g, "&amp;")
            .replace(/</g, "&lt;")
            .replace(/>/g, "&gt;")
            .replace(/"/g, "&quot;")
            .replace(/'/g, "&#039;");
    }

    /**
     * Highlights the clicked option button and enables submission.
     */
    function selectOption(buttonElement, optionKey) {
        if (isSubmitted) return;

        // Remove active styling from all options
        const allOptionBtns = optionsContainer.querySelectorAll('.option-btn');
        allOptionBtns.forEach(btn => btn.classList.remove('selected'));

        // Apply active highlights
        buttonElement.classList.add('selected');
        selectedOption = optionKey;
        submitBtn.disabled = false;
    }

    /**
     * Securely validates selected answer on the server.
     */
    async function submitAnswer() {
        if (isSubmitted) return;
        
        isSubmitted = true;
        clearInterval(timerInterval); // Stop ticking
        
        const question = questionsList[currentQuestionIndex];
        const csrfToken = getCsrfToken();

        // Lock button interactions immediately
        const allOptionBtns = optionsContainer.querySelectorAll('.option-btn');
        allOptionBtns.forEach(btn => {
            btn.disabled = true;
            if (btn.dataset.option !== selectedOption) {
                btn.classList.add('faded');
            }
        });

        try {
            const response = await fetch('/api/validate/', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'X-CSRFToken': csrfToken
                },
                body: JSON.stringify({
                    question_id: question.id,
                    selected_option: selectedOption
                })
            });

            if (!response.ok) {
                throw new Error('Server returned error during validation.');
            }

            const validation = await response.json();
            
            // Check results
            if (validation.is_correct) {
                score++;
                liveScoreBadge.textContent = `Score: ${score}`;
                playGlowAnimation(true);
            } else {
                playGlowAnimation(false);
            }

            // Highlight answers visually
            allOptionBtns.forEach(btn => {
                const optKey = btn.dataset.option;
                if (optKey === validation.correct_answer) {
                    btn.classList.remove('faded');
                    btn.classList.add('correct');
                } else if (optKey === selectedOption && !validation.is_correct) {
                    btn.classList.remove('faded');
                    btn.classList.add('wrong');
                }
            });

            // Adjust controls
            submitBtn.classList.add('hidden');
            
            // Check if final question
            if (currentQuestionIndex + 1 >= questionsList.length) {
                nextBtn.innerHTML = `Finish Quiz <i class="fa-solid fa-flag-checkered"></i>`;
            } else {
                nextBtn.innerHTML = `Next Question <i class="fa-solid fa-circle-arrow-right"></i>`;
            }
            nextBtn.classList.remove('hidden');

        } catch (error) {
            console.error('Validation Error:', error);
            // Fallback locally in case of network drops
            alert('Error validating answer. Proceeding to next question.');
            goToNextQuestion();
        }
    }

    /**
     * Handles timer expiry. Auto-locks options, reveals the correct option.
     */
    async function handleTimerExpiry() {
        isSubmitted = true;
        clearInterval(timerInterval);

        // Lock option interactions
        const allOptionBtns = optionsContainer.querySelectorAll('.option-btn');
        allOptionBtns.forEach(btn => {
            btn.disabled = true;
            btn.classList.add('faded');
        });

        // Flash timer widget
        timerWidget.className = 'timer-widget active danger';
        timerText.textContent = "0s";

        const question = questionsList[currentQuestionIndex];
        const csrfToken = getCsrfToken();

        try {
            // Fetch correct answer securely to display correct highlights
            const response = await fetch('/api/validate/', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'X-CSRFToken': csrfToken
                },
                body: JSON.stringify({
                    question_id: question.id,
                    selected_option: '' // Empty submission
                })
            });

            if (response.ok) {
                const validation = await response.json();
                
                // Highlight the correct option in green
                allOptionBtns.forEach(btn => {
                    if (btn.dataset.option === validation.correct_answer) {
                        btn.classList.remove('faded');
                        btn.classList.add('correct');
                    }
                });
            }
        } catch (error) {
            console.error('Timer expiry backend connection error:', error);
        }

        // Prompt visual feedback
        questionText.innerHTML = `<span style="color: var(--danger); font-weight:700;">[TIME OUT]</span> ${question.text}`;

        submitBtn.classList.add('hidden');
        if (currentQuestionIndex + 1 >= questionsList.length) {
            nextBtn.innerHTML = `Finish Quiz <i class="fa-solid fa-flag-checkered"></i>`;
        } else {
            nextBtn.innerHTML = `Next Question <i class="fa-solid fa-circle-arrow-right"></i>`;
        }
        nextBtn.classList.remove('hidden');
    }

    /**
     * Shifts to the next question.
     */
    function goToNextQuestion() {
        currentQuestionIndex++;
        displayQuestion();
    }

    // --- Dynamic Background Glow Effects ---
    
    function playGlowAnimation(isCorrect) {
        const quizCard = document.getElementById('quizCard');
        const color = isCorrect ? 'rgba(16, 185, 129, 0.2)' : 'rgba(244, 63, 94, 0.2)';
        quizCard.style.boxShadow = `0 0 50px ${color}`;
        
        setTimeout(() => {
            quizCard.style.boxShadow = '';
        }, 1000);
    }

    // --- Timer Mechanism ---

    function startTimer() {
        clearInterval(timerInterval);
        timeLeft = SECONDS_PER_QUESTION;
        
        // Reset timer widget states
        timerWidget.className = 'timer-widget active';
        timerText.textContent = `${timeLeft}s`;

        timerInterval = setInterval(() => {
            timeLeft--;
            timerText.textContent = `${timeLeft}s`;

            if (timeLeft <= 10 && timeLeft > 5) {
                timerWidget.className = 'timer-widget active warning';
            } else if (timeLeft <= 5) {
                timerWidget.className = 'timer-widget active danger';
            }

            if (timeLeft <= 0) {
                clearInterval(timerInterval);
                handleTimerExpiry();
            }
        }, 1000);
    }

    // --- Quiz Completion & Results Screen ---

    async function endQuiz() {
        clearInterval(timerInterval);
        switchScreen(resultsScreen);

        // Fill progress bar to max
        progressBar.style.width = '100%';

        // Calculations
        const total = questionsList.length;
        const percent = total > 0 ? Math.round((score / total) * 100) : 0;
        
        // Render stats counters
        statsCorrect.textContent = score;
        statsWrong.textContent = total - score;
        statsTime.textContent = "100%"; // User went all the way

        // Render circular progress gauge
        // Circumference: 2 * PI * r = 2 * 3.14159 * 50 = 314
        const circumference = 314;
        const offset = circumference - (circumference * percent / 100);
        
        // Animate stroke dashoffset slowly
        gaugeFill.style.strokeDasharray = `${circumference}`;
        gaugeFill.style.strokeDashoffset = `${circumference}`;
        
        setTimeout(() => {
            gaugeFill.style.strokeDashoffset = `${offset}`;
        }, 300);

        resultsPercent.textContent = `${percent}%`;
        resultsScoreText.textContent = `${score}/${total} Correct`;

        // Render curated feedback text
        if (percent === 100) {
            feedbackTitle.textContent = "Mastermind! Perfect Score!";
            resultsSummaryText.textContent = `Excellent job, ${studentName}! Flawless execution. Your name has been engraved at the top of our standings!`;
        } else if (percent >= 80) {
            feedbackTitle.textContent = "Magnificent Performance!";
            resultsSummaryText.textContent = `Superb job, ${studentName}! You have shown a strong, highly competent grasp of core programming techniques.`;
        } else if (percent >= 50) {
            feedbackTitle.textContent = "Good Job! Room for Growth";
            resultsSummaryText.textContent = `Good effort, ${studentName}! You solved several core problems. Try again to boost your standing on the board!`;
        } else {
            feedbackTitle.textContent = "Keep Practicing!";
            resultsSummaryText.textContent = `A valuable training run, ${studentName}! Review python types and django migrations, and retry to get a passing grade!`;
        }

        // --- SUBMIT ATTEMPT TO BACKEND ---
        try {
            const csrfToken = getCsrfToken();
            const response = await fetch('/api/submit-attempt/', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'X-CSRFToken': csrfToken
                },
                body: JSON.stringify({
                    student_name: studentName,
                    student_id: studentId,
                    score: score,
                    total_questions: total
                })
            });

            if (response.ok) {
                // Refresh classroom leaderboard dynamic scores
                loadLeaderboard();
            }
        } catch (error) {
            console.error('Failed to register score to server:', error);
        }
    }

    // --- Interactive Button Listeners ---
    
    startBtn.addEventListener('click', () => {
        const nameVal = studentNameInput.value.trim();
        const idVal = studentIdInput.value.trim();

        // Onboarding Form Validations
        if (!nameVal) {
            studentNameInput.focus();
            studentNameInput.style.borderColor = 'var(--danger)';
            return;
        } else {
            studentNameInput.style.borderColor = '';
        }

        if (!idVal) {
            studentIdInput.focus();
            studentIdInput.style.borderColor = 'var(--danger)';
            return;
        } else {
            studentIdInput.style.borderColor = '';
        }

        // Register profile
        studentName = nameVal;
        studentId = idVal;

        loadQuiz();
    });

    submitBtn.addEventListener('click', () => {
        submitAnswer();
    });

    nextBtn.addEventListener('click', () => {
        goToNextQuestion();
    });

    restartBtn.addEventListener('click', () => {
        currentQuestionIndex = 0;
        score = 0;
        switchScreen(welcomeScreen);
        progressBar.style.width = '0%';
        
        // Reset name inputs for next students
        studentNameInput.value = '';
        studentIdInput.value = '';
        studentName = '';
        studentId = '';
    });
});
